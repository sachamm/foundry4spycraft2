#!/usr/bin/env node
/**
 * Build step for the Spycraft 2.0 system.
 *
 *   src/data/*.json  ──►  module/rules/tables.mjs   (rules tables used by the engine)
 *                    ──►  packs/<name>/             (LevelDB compendium packs)
 *
 * src/data/*.json is the source of truth and is edited by hand. Run with `npm run build`.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, rmSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ClassicLevel } from "classic-level";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = f => JSON.parse(readFileSync(join(ROOT, "src/data", f), "utf8"));
const core = read("core.json");
const classes = read("classes.json");
const origins = read("origins.json");
const feats = read("feats.json");
const equipment = read("equipment.json");
const summaries = read("summaries.json");
const system = JSON.parse(readFileSync(join(ROOT, "system.json"), "utf8"));

const camel = s => {
  const parts = s.replace(/[^A-Za-z ]/g, " ").trim().split(/\s+/);
  return parts[0].toLowerCase() + parts.slice(1).map(p => p[0].toUpperCase() + p.slice(1).toLowerCase()).join("");
};
const id = (...parts) => createHash("sha1").update(parts.join("|")).digest("base64").replace(/[^A-Za-z0-9]/g, "").slice(0, 16);
const esc = s => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const p = s => (s ? `<p>${esc(s)}</p>` : "");
const SOURCE = "Spycraft 2.0 (summary)";
const missing = [];

/** Loose key for matching table ability names ("Behind the scenes II (DC 20)") to summary keys ("Behind the Scenes"). */
const loose = s => String(s).toLowerCase()
  .replace(/\([^)]*\)/g, " ").replace(/[“”"'’]/g, "").replace(/\b(i{1,3}|iv|v)\b/g, " ")
  .replace(/[+x×]?\s*\d+(d\d+)?(\/(session|mission|scene))?/g, " ").replace(/[^a-z ]/g, " ").replace(/\s+/g, " ").trim();
function lev(a, b) {
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++)
    d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return d[a.length][b.length];
}
/** Find the summary for a name: exact loose match, prefix match, then small edit distance. */
function lookupSummary(map, name) {
  const k = loose(name);
  const entries = Object.entries(map).map(([n, v]) => [loose(n), v]);
  let hit = entries.find(([n]) => n === k) ?? entries.find(([n]) => k.startsWith(n) || n.startsWith(k));
  if (!hit) {
    const best = entries.map(e => [lev(e[0], k), e]).sort((a, b) => a[0] - b[0])[0];
    if (best && best[0] <= Math.max(2, Math.floor(k.length / 5))) hit = best[1];
  }
  if (process.env.DEBUG_MATCH && hit && hit[0] !== k) console.log(`  match: "${k}" -> "${hit[0]}"`);
  return hit?.[1] ?? null;
}

/* ------------------------------------------------------------------ */
/*  Rules tables module                                                */
/* ------------------------------------------------------------------ */
const tablesSrc = `// GENERATED by tools/build-packs.mjs from src/data/core.json — do not edit by hand.
export const SKILLS = ${JSON.stringify(core.skills.map(({ row, ...s }) => s), null, 1)};
export const TABLES = ${JSON.stringify(core.tables, null, 1)};
`;
writeFileSync(join(ROOT, "module/rules/tables.mjs"), tablesSrc);

/* ------------------------------------------------------------------ */
/*  Compendium documents                                               */
/* ------------------------------------------------------------------ */
const stats = { coreVersion: system.compatibility.verified, systemId: "spycraft2", systemVersion: system.version };
function item(pack, name, type, img, sys, folder = null, sort = 0) {
  return { _id: id(pack, type, name), name, type, img, system: sys, effects: [], folder, sort, ownership: { default: 0 }, flags: {}, _stats: stats };
}
function folder(pack, name, sort = 0) {
  return { _id: id(pack, "folder", name), name, type: "Item", folder: null, sorting: "a", sort, color: null, flags: {}, _stats: stats };
}

const PROF = Object.fromEntries(core.tables.proficiencies.map(n => [n.toLowerCase(), camel(n)]));
const PENALTY = { unarmed: -2, blunt: -2, exoticBlunt: -6, edged: -4, exoticEdged: -8, hurled: -2, exoticHurled: -6, handgun: -4,
  rifle: -4, shotgun: -4, submachineGun: -4, tactical: -8, explosives: -8, guided: -10, indirectFire: -12, vehicleWeapon: 0 };
const ROMAN = { I: 1, II: 2, III: 3, IV: 4, V: 5 };

const packs = {};

// Classes
packs.classes = { label: "Classes", folders: [folder("classes", "Base Classes", 1), folder("classes", "Expert Classes", 2)], docs: [] };
for (const c of classes) {
  const sum = summaries.classes[c.name] ?? { core: "", abilities: {}, options: {} };
  if (!summaries.classes[c.name]) missing.push(`class ${c.name}`);
  const coreText = sum.core.replace(/^[^:]+:\s*/, "");
  const abilities = (c.abilities ?? []).map(a => {
    // Split "A, B. C" into components, but not inside quotes ("Any time, any place").
    const parts = String(a.name).match(/(?:"[^"]*"|“[^”]*”|\d[,.]\d|[^,.])+/g)?.map(x => x.trim()).filter(x => loose(x)) ?? [];
    const text = parts.map(part => {
      const t = lookupSummary(sum.abilities, part);
      if (!t) missing.push(`${c.name} ${a.level}: ${part}`);
      return t ? (parts.length > 1 ? `${part.trim()}: ${t}` : t) : "";
    }).filter(Boolean).join(" ");
    return { level: a.level, name: a.name, description: text };
  });
  const desc = [
    `<p><strong>Core Ability — ${esc(c.coreAbility.name)}:</strong> ${esc(coreText)}</p>`,
    `<p><strong>Skill points:</strong> ${c.skillPoints} + Int modifier per level (×4 at Career Level 1). <strong>Vitality:</strong> ${c.vitality} + Con modifier per level.</p>`
  ].join("");
  packs.classes.docs.push(item("classes", c.name, "class", c.expert ? "icons/svg/upgrade.svg" : "icons/svg/book.svg", {
    description: desc, source: SOURCE,
    identifier: c.key, expert: c.expert, skillPoints: c.skillPoints, vitalityDie: c.vitality, proficiencies: c.proficiencies,
    coreAbility: { name: c.coreAbility.name, description: coreText }, classSkills: c.classSkills, table: c.table, abilities,
    choiceLists: c.choiceLists.map(L => ({ key: L.key, name: L.name, options: L.options.map(o => {
      const tree = Object.keys(summaries.feats).length && feats.some(f => f.tree === o.name) ? o.name : null;
      const d = lookupSummary(sum.options, o.name)
        ?? (tree ? `Gain a${/^[AEIOU]/.test(tree) ? "n" : ""} ${tree} feat.` : null)
        ?? ({ Contact: "Gain a new associate-grade contact.", "Gear Feat": "Gain a Gear feat." })[o.name]
        ?? lookupSummary(sum.abilities, o.name);
      if (d === null) missing.push(`${c.name} option ${o.name}`);
      return { index: o.index, name: o.name, description: d ?? "", bonuses: o.bonuses };
    }) })),
    choiceSchedule: c.choiceSchedule ?? [], choices: {}, bonuses: (c.bonuses ?? []).map(b => ({ level: 0, ...b })),
    featGrants: c.featGrants ?? [], requirements: c.requirements ?? null
  }, packs.classes.folders[c.expert ? 1 : 0]._id, c.num));
}

// Origins
packs.origins = { label: "Origins", folders: [folder("origins", "Talents", 1), folder("origins", "Specialties", 2)], docs: [] };
for (const [list, fi] of [[origins.talents, 0], [origins.specialties, 1]]) {
  for (const o of list) {
    packs.origins.docs.push(item("origins", o.name, "origin", fi ? "icons/svg/mystery-man.svg" : "icons/svg/aura.svg", {
      description: p(summaries.origins[o.name] ?? (missing.push(`origin ${o.name}`), "")), source: SOURCE, originType: o.originType,
      bonuses: o.bonuses.map(b => ({ level: 0, ...b })), grants: o.grants.map(g => g.feat)
    }, packs.origins.folders[fi]._id, o.num));
  }
}

// Feats
const trees = [...new Set(feats.map(f => f.tree))].sort();
packs.feats = { label: "Feats", folders: trees.map((t, i) => folder("feats", t, i)), docs: [] };
const featFolder = Object.fromEntries(trees.map((t, i) => [t, packs.feats.folders[i]._id]));
for (const f of feats) {
  packs.feats.docs.push(item("feats", f.name, "feat", "icons/svg/combat.svg", {
    description: p(summaries.feats[f.name] ?? (missing.push(`feat ${f.name}`), "")), source: SOURCE, tree: camel(f.tree),
    prerequisites: f.prerequisites, prerequisitesNotChecked: f.notChecked, ranks: 1, granted: false, grantSource: "",
    bonuses: f.bonuses.map(b => ({ level: 0, ...b }))
  }, featFolder[f.tree], f.row));
}

// Weapons
const wprofs = [...new Set(equipment.weapons.map(w => w.proficiency))];
packs.weapons = { label: "Weapons", folders: wprofs.map((n, i) => folder("weapons", n, i)), docs: [] };
for (const w of equipment.weapons) {
  const prof = PROF[w.proficiency.toLowerCase()] ?? camel(w.proficiency);
  const [err = "1", thr = "20"] = String(w.errorThreat ?? "").split("/");
  const error = parseInt(err.split("-").pop()) || 1;
  const threat = parseInt(thr) || 20;
  packs.weapons.docs.push(item("weapons", w.name, "weapon", "icons/svg/sword.svg", {
    description: "", source: "Spycraft 2.0", quantity: 1, equipped: false, weight: Number(w.weight) || 0,
    caliber: ROMAN[w.caliber] ?? 1, pick: "", reserve: false, common: false,
    proficiency: prof, damage: String(w.damage ?? ""), error, threat, errorThreat: String(w.errorThreat ?? ""),
    ammo: String(w.ammo ?? ""), recoil: Number(w.recoil) || 0, range: Number(w.range) || 0, sizeHands: String(w.sizeHands ?? ""),
    qualities: String(w.qualities ?? ""), untrainedPenalty: PENALTY[prof] ?? -4
  }, packs.weapons.folders[wprofs.indexOf(w.proficiency)]._id, w.num));
}

// Armor
packs.armor = { label: "Armor", folders: [], docs: [] };
for (const a of equipment.armor) {
  const [dr = 0, drSub = 0] = String(a.dr ?? "0/0").split("/").map(n => parseInt(n) || 0);
  packs.armor.docs.push(item("armor", a.name, "armor", "icons/svg/shield.svg", {
    description: "", source: "Spycraft 2.0", quantity: 1, equipped: false, weight: Number(a.weight) || 0,
    caliber: ROMAN[a.caliber] ?? 0, pick: "", reserve: false, common: false,
    damageReduction: dr, damageReductionSubdual: drSub, resistances: String(a.resist ?? ""),
    defensePenalty: Number(a.defensePenalty) || 0, armorCheck: Number(a.acp) || 0, speedPenalty: Number(a.speed) || 0,
    notice: String(a.notice ?? "")
  }, null, a.num));
}

if (missing.length) console.warn(`No summary for ${missing.length} entr${missing.length === 1 ? "y" : "ies"}:\n  ${missing.join("\n  ")}`);

/* ------------------------------------------------------------------ */
/*  Write LevelDB                                                      */
/* ------------------------------------------------------------------ */
for (const [name, pack] of Object.entries(packs)) {
  const dir = join(ROOT, "packs", name);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const db = new ClassicLevel(dir, { valueEncoding: "json" });
  const batch = db.batch();
  for (const f of pack.folders) batch.put(`!folders!${f._id}`, f);
  for (const d of pack.docs) batch.put(`!items!${d._id}`, d);
  await batch.write();
  await db.compactRange("\x00", "\xff");
  await db.close();
  console.log(`packs/${name}: ${pack.docs.length} items, ${pack.folders.length} folders`);
}

// Keep system.json's pack list in sync.
system.packs = Object.entries(packs).map(([name, pack]) => ({
  name, label: pack.label, path: `packs/${name}`, type: "Item", system: "spycraft2",
  ownership: { PLAYER: "OBSERVER", ASSISTANT: "OWNER" }, flags: {}
}));
system.packFolders = [{ name: "Spycraft 2.0", sorting: "m", color: "#1d2b3a", packs: Object.keys(packs) }];
writeFileSync(join(ROOT, "system.json"), JSON.stringify(system, null, 2) + "\n");
console.log("module/rules/tables.mjs and system.json updated");
